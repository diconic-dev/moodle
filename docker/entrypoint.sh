#!/bin/sh
# Generates config.php from environment variables, then hands PID 1 to php-fpm.
set -eu

DB_HOST="${MOODLE_DB_HOST:-db}"
DB_PORT="${MOODLE_DB_PORT:-3306}"
DB_NAME="${MOODLE_DB_NAME:-moodle}"
DB_USER="${MOODLE_DB_USER:-moodle}"
DB_PASS="${MOODLE_DB_PASSWORD:-}"
DB_TYPE="${MOODLE_DB_TYPE:-mariadb}"
WWWROOT="${MOODLE_WWWROOT:-http://localhost:8080}"
DATAROOT="${MOODLE_DATAROOT:-/var/www/moodledata}"
PREFIX="${MOODLE_DB_PREFIX:-mdl_}"

log() { printf '[moodle-entrypoint] %s\n' "$*" >&2; }

##############################################################################
# 1. Wait for the database.
# A startup race otherwise surfaces as "Error reading from database" instead of
# an honest timeout.
##############################################################################
probe_db() {
    DB_PROBE_HOST="$DB_HOST" DB_PROBE_PORT="$DB_PORT" php -r '
        $h = @fsockopen(getenv("DB_PROBE_HOST"), (int) getenv("DB_PROBE_PORT"), $e, $s, 2);
        if ($h) { fclose($h); exit(0); }
        exit(1);
    ' 2>/dev/null
}

log "waiting for database ${DB_HOST}:${DB_PORT} ..."
tries=0
max_tries="${MOODLE_DB_WAIT_SECONDS:-60}"
until probe_db; do
    tries=$((tries + 1))
    if [ "$tries" -ge "$max_tries" ]; then
        log "ERROR: database unreachable after ${max_tries}s — giving up"
        exit 1
    fi
    sleep 1
done
log "database is reachable"

##############################################################################
# 2. Directories Moodle writes into.
##############################################################################
mkdir -p "$DATAROOT"
if [ "$(id -u)" = "0" ]; then
    chown www-data:www-data "$DATAROOT" 2>/dev/null || true
fi

##############################################################################
# 3. Render config.php once.
# Never overwritten afterwards: the installer and later admin edits write into
# this file, so clobbering it on restart would silently revert settings.
##############################################################################
CONFIG=/var/www/moodle/config.php

if [ -f "$CONFIG" ]; then
    log "config.php already present — leaving it untouched"
else
    log "rendering config.php (wwwroot=${WWWROOT})"

    # Escape backslashes and single quotes for single-quoted PHP strings.
    php_esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e "s/'/\\\\'/g"; }

    {
        echo '<?php'
        echo '// Generated by the container entrypoint. This file is preserved on'
        echo '// restart, so settings changed through the admin UI survive redeploys.'
        echo 'unset($CFG);'
        echo 'global $CFG;'
        echo '$CFG = new stdClass();'
        echo ''
        echo "\$CFG->dbtype    = '"$(php_esc "$DB_TYPE")"';"
        echo "\$CFG->dblibrary = 'native';"
        echo "\$CFG->dbhost    = '"$(php_esc "$DB_HOST")"';"
        echo "\$CFG->dbname    = '"$(php_esc "$DB_NAME")"';"
        echo "\$CFG->dbuser    = '"$(php_esc "$DB_USER")"';"
        echo "\$CFG->dbpass    = '"$(php_esc "$DB_PASS")"';"
        echo "\$CFG->prefix    = '"$(php_esc "$PREFIX")"';"
        echo '$CFG->dboptions = ['
        echo "    'dbport'      => '"$(php_esc "$DB_PORT")"',"
        echo "    'dbsocket'    => '',"
        echo "    'dbcollation' => 'utf8mb4_unicode_ci',"
        echo '];'
        echo ''
        echo "\$CFG->wwwroot  = '"$(php_esc "$WWWROOT")"';"
        echo "\$CFG->dataroot = '"$(php_esc "$DATAROOT")"';"
        echo "\$CFG->admin    = 'admin';"
        echo '$CFG->directorypermissions = 02777;'
        echo ''
        echo '// Keep generated URLs correct behind a reverse proxy / LB.'
        echo "\$CFG->reverseproxy = ${MOODLE_REVERSEPROXY:-0};"
        echo "\$CFG->sslproxy     = ${MOODLE_SSLPROXY:-0};"
        echo ''
        echo "require_once(__DIR__ . '/lib/setup.php');"
    } > "$CONFIG"

    chmod 0640 "$CONFIG"
    if [ "$(id -u)" = "0" ]; then
        chown www-data:www-data "$CONFIG"
    fi
    log "config.php written"
fi

##############################################################################
# 4. Hand off to the given command.
##############################################################################
log "starting: $*"
exec "$@"